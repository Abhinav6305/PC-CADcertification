// Regenerates js/data.js from data/participants.csv
// Usage: node scripts/build-data.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const csv = fs.readFileSync(path.join(root, "data", "participants.csv"), "utf8");

function parseCSV(text) {
  const rows = [];
  let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter(r => r.some(v => v.trim()));
}

const [head, ...body] = parseCSV(csv);
const idx = Object.fromEntries(head.map((h, i) => [h.trim().toLowerCase(), i]));
const VALID = new Set(["", "first-place", "runner-up"]);

const seen = new Set();
const people = body.map((r, n) => {
  const p = {
    name: (r[idx.name] || "").trim().replace(/\s+/g, " "),
    roll: (r[idx.roll] || "").trim().toUpperCase(),
    year: (r[idx.year] || "").trim(),
    award: (r[idx.award] || "").trim().toLowerCase(),
    team: (r[idx.team] || "").trim(),
  };
  if (!p.name || !p.roll) throw new Error(`Row ${n + 2}: name and roll are required`);
  if (!VALID.has(p.award)) throw new Error(`Row ${n + 2}: award must be blank, first-place or runner-up`);
  if (seen.has(p.roll)) throw new Error(`Row ${n + 2}: duplicate roll number ${p.roll}`);
  seen.add(p.roll);
  return p;
});

const out =
  "// AUTO-GENERATED by scripts/build-data.js from data/participants.csv — do not edit by hand\n" +
  "window.PARTICIPANTS = " + JSON.stringify(people, null, 2) + ";\n";
fs.writeFileSync(path.join(root, "js", "data.js"), out);

const c = a => people.filter(p => p.award === a).length;
console.log(`js/data.js written: ${people.length} participants (${c("first-place")} first place, ${c("runner-up")} runner-up)`);
